import fs from 'node:fs';
import ts from 'typescript';
import assert from 'node:assert/strict';
import {File} from 'node:buffer';
const source=ts.transpileModule(fs.readFileSync('supabase/functions/submit-pilot/validation.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {validatePayload,validateUpload,MAX_FILE_SIZE}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const host={id:crypto.randomUUID(),kind:'host',timezone:'America/New_York',fields:{name:'Test Host',email:'HOST@example.com',source:'Slack channel',device:'PC',specs:'RTX 4060',idleTime:'A few hours a day',availability:'Yes',hostConsent:'yes'}};
assert.equal(validatePayload(host,false).email,'host@example.com');
assert.throws(()=>validatePayload({...host,fields:{...host.fields,specs:' '}},false));
assert.throws(()=>validatePayload(host,true));
assert.throws(()=>validatePayload({...host,timezone:'not-a-timezone'},false));
const job={id:crypto.randomUUID(),kind:'job',timezone:'America/New_York',deadlineUtc:new Date(Date.now()+86400000).toISOString(),fields:{name:'Test User',email:'test@example.com',courses:['NLP'],currentCompute:'Colab',frameworks:['PyTorch'],hitLimit:'Yes',description:'Test only',runtime:'Under 10 min',paymentContact:'test',paymentMethod:'Venmo',paymentConsent:'yes',codeLink:'https://example.com/job.py'}};
assert.equal(validatePayload(job,false).kind,'job');
assert.throws(()=>validatePayload({...job,deadlineUtc:'2020-01-01'},false));
assert.throws(()=>validatePayload({...job,fields:{...job.fields,codeLink:'javascript:alert(1)'}},false));
assert.throws(()=>validatePayload({...job,fields:{...job.fields,codeLink:''}},false));
assert.equal(validatePayload({...job,fields:{...job.fields,codeLink:''}},true).kind,'job');
assert.throws(()=>validatePayload({...job,fields:{...job.fields,paymentConsent:'no'}},false));
await validateUpload(new File(['print("test")'], 'job.py'));
await validateUpload(new File(['{"cells":[],"nbformat":4}'], 'job.ipynb'));
await assert.rejects(()=>validateUpload(new File(['not a zip'],'job.zip')));
await assert.rejects(()=>validateUpload(new File(['not json'],'job.ipynb')));
await assert.rejects(()=>validateUpload(new File([new Uint8Array([0,1,2])],'job.py')));
await assert.rejects(()=>validateUpload(new File(['test'],'job.exe')));
await assert.rejects(()=>validateUpload(new File([new Uint8Array(MAX_FILE_SIZE+1)],'job.zip')));
console.log('Passed: host requirements, job requirements, deadlines, links, consent, timezones, file formats, binary rejection and upload limits.');
