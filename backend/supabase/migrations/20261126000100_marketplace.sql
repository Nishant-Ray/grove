-- Marketplace: renters find compatible hosts and book them; hosts run the job lifecycle
-- from the web dashboard until a desktop agent exists.
--
-- Security model: every function below that changes jobs or devices is SECURITY DEFINER and
-- executable only by service_role. FastAPI verifies the signed-in user and passes them as
-- p_actor, so users cannot call these functions directly through PostgREST with their own JWT.

create extension if not exists pg_cron;

alter table public.grove_settings
    add column batch_start_hours int not null default 24 check (batch_start_hours > 0),
    add column request_expiry_minutes int not null default 60 check (request_expiry_minutes > 0),
    add column heartbeat_minutes int not null default 5 check (heartbeat_minutes > 0);

-- Approximate location: mean of Census 2024 ZCTA internal points per ZIP3 prefix.
-- Private; only read by recommend_hosts so host ZIP codes are never exposed.
create table public.zip3_centroids (
    zip3 char(3) primary key check (zip3 ~ '^[0-9]{3}$'),
    lat numeric(7,4) not null check (lat between -90 and 90),
    lng numeric(7,4) not null check (lng between -180 and 180)
);
alter table public.zip3_centroids enable row level security;
revoke all on public.zip3_centroids from public, anon, authenticated;

alter table public.compute_jobs
    drop constraint compute_jobs_status_check,
    add constraint compute_jobs_status_check check (status in
        ('requested','scheduled','running','completed','failed','cancelled','declined')),
    add column host_device_id uuid references public.host_devices(id) on delete set null,
    add column host_id uuid references auth.users(id) on delete set null,
    add column gpu_model text references public.gpu_rates(gpu_model) on update cascade,
    add column priority text references public.priority_levels(id) on update cascade,
    add column est_hours numeric(6,2) check (est_hours is null or est_hours > 0),
    add column min_vram_gb int check (min_vram_gb is null or min_vram_gb >= 0),
    -- Prices are snapshotted from a server-side quote when the job is booked.
    add column rate_per_hr numeric(8,4) check (rate_per_hr is null or rate_per_hr > 0),
    add column host_payout_per_hr numeric(8,4) check (host_payout_per_hr is null or host_payout_per_hr > 0),
    add column reserve_micros bigint check (reserve_micros is null or reserve_micros >= 0),
    add column charged_micros bigint check (charged_micros is null or charged_micros >= 0),
    add column code_link text check (code_link is null or (code_link ~ '^https?://' and length(code_link) <= 2000)),
    add column accepted_at timestamptz,
    -- Deadline for the next step: acceptance while requested, starting while scheduled.
    add column start_by timestamptz,
    add column outcome_reason text check (outcome_reason is null or outcome_reason in
        ('completed','renter_stopped','job_error','host_side','no_show','host_cancelled',
         'renter_cancelled','declined','not_accepted'));

-- One open booking per device: prevents double booking even under concurrent requests.
create unique index compute_jobs_one_active_per_device on public.compute_jobs(host_device_id)
    where status in ('requested','scheduled','running');
create index compute_jobs_host_date_idx on public.compute_jobs(host_id, requested_at desc, id desc);
create policy read_hosted_jobs on public.compute_jobs for select to authenticated
    using (host_id = (select auth.uid()));

-- Recommendations --------------------------------------------------------------------
-- Candidates are available, recently seen, not busy, not the renter's own, and have enough
-- VRAM. Pricing and the electricity floor are applied in Python (app/pricing.py).
create function public.recommend_hosts(p_actor uuid, p_priority text, p_min_vram int,
                                       p_gpu_model text, p_renter_zip text)
returns table (
    device_id uuid, device_name text, host_name text, gpu_model text, gpu_label text, vram_gb int,
    base_rate_usd_hr numeric, power_kw numeric, usd_per_kwh numeric, green_energy boolean,
    state text, distance_miles numeric, priority_multiplier numeric, host_share numeric,
    floor_margin numeric, reserve_multiplier numeric
)
language plpgsql stable security definer set search_path = ''
as $$
declare
    renter public.zip3_centroids;
begin
    if not exists (select 1 from public.priority_levels where id = p_priority) then
        raise exception 'UNKNOWN_PRIORITY';
    end if;
    if not exists (select 1 from public.grove_settings) then
        raise exception 'PRICING_UNAVAILABLE';
    end if;
    select * into renter from public.zip3_centroids where zip3 = left(p_renter_zip, 3);
    return query
    select d.id, d.name, coalesce(nullif(trim(u.raw_user_meta_data->>'display_name'), ''), 'Grove host'),
           g.gpu_model, g.label, v.vram, g.base_rate_usd_hr, g.power_kw + s.system_overhead_kw,
           coalesce(d.usd_per_kwh_override, st.usd_per_kwh, us.usd_per_kwh), d.green_energy,
           z.state::text,
           case when renter.zip3 is not null and c.zip3 is not null then
               round((3958.8 * 2 * asin(sqrt(
                   power(sin(radians(c.lat - renter.lat) / 2), 2) +
                   cos(radians(renter.lat)) * cos(radians(c.lat)) *
                   power(sin(radians(c.lng - renter.lng) / 2), 2))))::numeric, 1)
           end,
           p.multiplier, s.host_share, s.floor_margin, s.reserve_multiplier
    from public.host_devices d
    join public.gpu_rates g on g.gpu_model = d.gpu_model and g.active
    join auth.users u on u.id = d.owner_id
    cross join public.grove_settings s
    join public.priority_levels p on p.id = p_priority
    cross join lateral (select coalesce(case when (d.specs->>'vram_gb') ~ '^[0-9]{1,6}$'
                                             then (d.specs->>'vram_gb')::int end, g.vram_gb) as vram) v
    left join public.zip3_ranges z on left(d.zip, 3) between z.zip3_start and z.zip3_end
    left join public.electricity_rates st on st.state = z.state
    left join public.electricity_rates us on us.state = 'US'
    left join public.zip3_centroids c on c.zip3 = left(d.zip, 3)
    where d.availability = 'available'
      and d.owner_id <> p_actor
      and d.last_seen_at > now() - make_interval(mins => s.heartbeat_minutes)
      and v.vram >= coalesce(p_min_vram, 0)
      and (p_gpu_model is null or d.gpu_model = p_gpu_model)
      and not exists (select 1 from public.compute_jobs j where j.host_device_id = d.id
                      and j.status in ('requested','scheduled','running'))
    order by g.base_rate_usd_hr, d.id
    limit 200;
end $$;

-- Host presence: the open host dashboard marks all of the host's devices as seen.
create function public.device_heartbeat(p_actor uuid)
returns int
language sql security definer set search_path = ''
as $$
    with seen as (
        update public.host_devices set last_seen_at = now() where owner_id = p_actor returning 1
    )
    select count(*)::int from seen;
$$;

-- Booking ------------------------------------------------------------------------------
create function public.create_job(p_actor uuid, p_device_id uuid, p_name text, p_priority text,
                                  p_hours numeric, p_min_vram int, p_code_link text,
                                  p_rate numeric, p_payout numeric, p_reserve_micros bigint)
returns public.compute_jobs
language plpgsql security definer set search_path = ''
as $$
declare
    s public.grove_settings;
    d public.host_devices;
    j public.compute_jobs;
    vram int;
    auto boolean;
begin
    select * into s from public.grove_settings;
    if not found then raise exception 'PRICING_UNAVAILABLE'; end if;
    select * into d from public.host_devices where id = p_device_id for update;
    if not found then raise exception 'DEVICE_NOT_FOUND'; end if;
    if d.owner_id = p_actor then raise exception 'OWN_DEVICE'; end if;
    if d.availability <> 'available' or d.gpu_model is null or d.last_seen_at is null
       or d.last_seen_at <= now() - make_interval(mins => s.heartbeat_minutes) then
        raise exception 'DEVICE_UNAVAILABLE';
    end if;
    select coalesce(case when (d.specs->>'vram_gb') ~ '^[0-9]{1,6}$' then (d.specs->>'vram_gb')::int end,
                    g.vram_gb) into vram
    from public.gpu_rates g where g.gpu_model = d.gpu_model;
    if vram < coalesce(p_min_vram, 0) then raise exception 'NOT_ENOUGH_VRAM'; end if;

    auto := coalesce(d.specs->>'acceptance', 'automatic') = 'automatic';
    begin
        insert into public.compute_jobs (
            owner_id, host_id, host_device_id, name, status, gpu_model, priority, est_hours,
            min_vram_gb, code_link, rate_per_hr, host_payout_per_hr, reserve_micros,
            accepted_at, scheduled_at, start_by)
        values (
            p_actor, d.owner_id, d.id, p_name, case when auto then 'scheduled' else 'requested' end,
            d.gpu_model, p_priority, p_hours, p_min_vram, nullif(trim(p_code_link), ''), p_rate,
            p_payout, p_reserve_micros,
            case when auto then now() end, case when auto then now() end,
            now() + case
                when not auto then make_interval(mins => s.request_expiry_minutes)
                when p_priority = 'batch' then make_interval(hours => s.batch_start_hours)
                else make_interval(mins => s.no_show_minutes) end)
        returning * into j;
    exception when unique_violation then
        raise exception 'DEVICE_BUSY';
    end;
    return j;
end $$;

-- Lifecycle ------------------------------------------------------------------------------
--   requested --accept--> scheduled --start--> running --complete--> completed
--   requested --decline--> declined            running --fail_host/fail_job--> failed
--   requested|scheduled --cancel--> cancelled  running --stop (renter)--> completed
-- Charges: completed, renter stop and job errors bill elapsed seconds, capped at the reserve.
-- Host-side failures, cancellations and no-shows are never charged.
create function public.job_action(p_actor uuid, p_job_id uuid, p_action text, p_summary text default null)
returns public.compute_jobs
language plpgsql security definer set search_path = ''
as $$
declare
    s public.grove_settings;
    j public.compute_jobs;
    is_host boolean;
    is_renter boolean;
    usage bigint;
begin
    select * into s from public.grove_settings;
    select * into j from public.compute_jobs where id = p_job_id for update;
    if not found or (j.owner_id <> p_actor and j.host_id is distinct from p_actor) then
        raise exception 'JOB_NOT_FOUND';
    end if;
    is_host := j.host_id = p_actor;
    is_renter := j.owner_id = p_actor;
    if j.started_at is not null then
        usage := least(coalesce(j.reserve_micros, 9223372036854775807),
                       round(j.rate_per_hr * floor(extract(epoch from now() - j.started_at)) / 3600 * 1000000)::bigint);
    end if;

    if p_action not in ('accept','decline','start','complete','fail_host','fail_job','stop','cancel') then
        raise exception 'INVALID_ACTION';
    elsif p_action in ('accept','decline','start','complete','fail_host','fail_job') and not is_host then
        raise exception 'NOT_ALLOWED';
    elsif p_action = 'stop' and not is_renter then
        raise exception 'NOT_ALLOWED';
    end if;

    if p_action = 'accept' and j.status = 'requested' then
        update public.compute_jobs set status = 'scheduled', accepted_at = now(), scheduled_at = now(),
            start_by = now() + case when j.priority = 'batch' then make_interval(hours => s.batch_start_hours)
                                    else make_interval(mins => s.no_show_minutes) end
        where id = j.id returning * into j;
    elsif p_action = 'decline' and j.status = 'requested' then
        update public.compute_jobs set status = 'declined', outcome_reason = 'declined',
            finished_at = now(), charged_micros = 0, start_by = null
        where id = j.id returning * into j;
    elsif p_action = 'start' and j.status = 'scheduled' then
        update public.compute_jobs set status = 'running', started_at = now(), start_by = null
        where id = j.id returning * into j;
    elsif p_action in ('complete','fail_job','stop') and j.status = 'running' then
        update public.compute_jobs set
            status = case when p_action = 'fail_job' then 'failed' else 'completed' end,
            outcome_reason = case p_action when 'complete' then 'completed' when 'stop' then 'renter_stopped'
                                           else 'job_error' end,
            finished_at = now(), charged_micros = usage, progress = case when p_action = 'fail_job' then progress else 100 end,
            result_summary = coalesce(left(nullif(trim(p_summary), ''), 1000), result_summary)
        where id = j.id returning * into j;
    elsif p_action = 'fail_host' and j.status = 'running' then
        update public.compute_jobs set status = 'failed', outcome_reason = 'host_side', finished_at = now(),
            charged_micros = 0, result_summary = coalesce(left(nullif(trim(p_summary), ''), 1000), result_summary)
        where id = j.id returning * into j;
    elsif p_action = 'cancel' and is_renter and j.status in ('requested','scheduled') then
        update public.compute_jobs set status = 'cancelled', outcome_reason = 'renter_cancelled',
            finished_at = now(), charged_micros = 0, start_by = null
        where id = j.id returning * into j;
    elsif p_action = 'cancel' and is_host and j.status = 'scheduled' then
        update public.compute_jobs set status = 'cancelled', outcome_reason = 'host_cancelled',
            finished_at = now(), charged_micros = 0, start_by = null
        where id = j.id returning * into j;
    elsif p_action = 'cancel' and not is_renter then
        raise exception 'NOT_ALLOWED';
    else
        raise exception 'INVALID_TRANSITION';
    end if;
    return j;
end $$;

-- Requests nobody accepted and accepted jobs that never started free the device again.
create function public.expire_jobs()
returns int
language sql security definer set search_path = ''
as $$
    with expired as (
        update public.compute_jobs
        set status = 'cancelled', finished_at = now(), charged_micros = 0, start_by = null,
            outcome_reason = case when status = 'requested' then 'not_accepted' else 'no_show' end
        where status in ('requested','scheduled') and start_by < now()
        returning 1
    )
    select count(*)::int from expired;
$$;

